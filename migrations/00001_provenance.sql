-- Provenance: where every number comes from (source -> dataset -> release).

-- +goose Up
CREATE TABLE source (
    source_id    TEXT PRIMARY KEY,               -- short slug, e.g. 'czso', 'mfcr', 'pcr'
    source_name  TEXT NOT NULL,
    homepage_url TEXT
);

CREATE TABLE dataset (
    dataset_id   TEXT PRIMARY KEY,               -- mirrors the source's own dataset code
    source_id    TEXT NOT NULL REFERENCES source (source_id),
    dataset_name TEXT NOT NULL
);

CREATE INDEX dataset_source_id_idx ON dataset (source_id);

CREATE TABLE release (
    release_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id   TEXT NOT NULL REFERENCES dataset (dataset_id),
    label        TEXT NOT NULL,
    published_at DATE NOT NULL,
    retrieved_at DATE NOT NULL,
    source_url   TEXT,
    raw_uri      TEXT NOT NULL,                  -- link to the raw dataset file as retrieved
    loading_code TEXT NOT NULL,                  -- link to the code that loaded this release
    code_version TEXT NOT NULL
        CHECK (code_version ~ '^[0-9a-f]{7,64}$'), -- git SHA (short or full, SHA-1 or SHA-256)
    supersedes   BIGINT REFERENCES release (release_id),
    notes        TEXT,
    CHECK (supersedes IS DISTINCT FROM release_id)
);

CREATE INDEX release_dataset_id_idx ON release (dataset_id);
CREATE INDEX release_supersedes_idx ON release (supersedes);

-- +goose Down
DROP TABLE release;
DROP TABLE dataset;
DROP TABLE source;
